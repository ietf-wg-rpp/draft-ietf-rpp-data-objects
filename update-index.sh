#!/usr/bin/env bash
# update-index.sh — regenerate the Document Index into .agent-index.md.
# Adapted for the mmark / Markdown authoring track of this repository.
# Usage: ./update-index.sh [src/draft-kowalik-rpp-data-objects.md]
set -euo pipefail

INDEX_MD=".agent-index.md"

# --- locate the source draft -------------------------------------------------
SRC="${1:-$(ls -1 src/draft-*-data-objects.md 2>/dev/null | sort | tail -n1)}"
[ -n "${SRC:-}" ] && [ -f "$SRC" ] || { echo "source draft not found" >&2; exit 1; }

# --- build the table ---------------------------------------------------------
# Markdown/mmark heading detection: leading "#".."####" then a space.
#   Level = number of leading '#'.
# Anchors (mmark): "{#anchor}" trailing the heading text.
# Each section's line range runs from its heading line through the line before
# the next same-or-shallower heading (EOF for the last heading).
TABLE=$(awk '
  function emit(lvl, title, anchor, start, end,   pad, i, a) {
    pad=""; for (i=1;i<lvl;i++) pad=pad "&nbsp;&nbsp;"
    a = (anchor=="") ? "" : "`{#" anchor "}`"
    printf "| %d | %s%s | %s | %d\342\200\223%d |\n", lvl, pad, title, a, start, end
  }
  /^#+ / {
    # parse this heading
    line=$0
    n=line; sub(/[^#].*/,"",n); lvl=length(n)
    if (lvl > 4) next
    # close the pending heading at (NR-1)
    if (have) emit(plvl, ptitle, panchor, pstart, NR-1)
    title=line; sub(/^#+ +/,"",title)
    anchor=""
    if (match(title, /\{#[^}]+\}/)) {
      anchor=substr(title, RSTART+2, RLENGTH-3)
      sub(/ *\{#[^}]+\}/,"",title)
    }
    plvl=lvl; ptitle=title; panchor=anchor; pstart=NR; have=1
  }
  END { if (have) emit(plvl, ptitle, panchor, pstart, NR) }
' "$SRC")

# --- write the index file (fully generated, overwritten on every run) --------
{
  printf '# Document Index\n\n'
  printf '_Generated by `./update-index.sh` from `%s` — do not edit by hand._\n\n' "$SRC"
  printf '| Level | Title | Anchor | Lines |\n|-------|-------|--------|-------|\n'
  printf '%s\n' "$TABLE"
} > "$INDEX_MD.tmp" && mv "$INDEX_MD.tmp" "$INDEX_MD"

echo "Document Index written to $INDEX_MD from $SRC"
